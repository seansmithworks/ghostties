// @ghostties/contract — the shapes the web app, the mobile app and the Mac
// app's cloud bridge all agree on. Mirrors cloud/supabase/migrations exactly:
// row types are what `select *` returns, RPC types are the database functions.
//
// No runtime dependencies and no Node/Deno-only imports, so Metro, Next and
// tsc can all consume the source directly.

// MARK: - Enums (string unions + runtime lists)

export const AGENT_ROLES = ["chief_of_staff", "general_manager", "worker"] as const;
export type AgentRole = (typeof AGENT_ROLES)[number];

/** Same vocabulary as the Mac sidebar's ClaudeStateStore.Kind, plus offline. */
export const AGENT_STATUSES = [
  "busy",
  "idle",
  "needs_input",
  "needs_permission",
  "ended",
  "offline",
] as const;
export type AgentStatus = (typeof AGENT_STATUSES)[number];

export const DESK_KINDS = ["mac", "cloud"] as const;
export type DeskKind = (typeof DESK_KINDS)[number];

export const AUTHOR_KINDS = ["user", "agent", "system"] as const;
export type AuthorKind = (typeof AUTHOR_KINDS)[number];

export const MESSAGE_KINDS = ["text", "status", "ask", "answer", "handoff"] as const;
export type MessageKind = (typeof MESSAGE_KINDS)[number];

export const ASK_KINDS = ["question", "permission", "decision"] as const;
export type AskKind = (typeof ASK_KINDS)[number];

export const ASK_STATUSES = ["open", "answered", "expired", "cancelled"] as const;
export type AskStatus = (typeof ASK_STATUSES)[number];

/** On-disk values from GhosttiesCore.TaskLane. "done" displays as "graveyard". */
export const TASK_LANES = ["inbox", "backlog", "running", "needs-you", "review", "done"] as const;
export type TaskLane = (typeof TASK_LANES)[number];

export const TASK_PRIORITIES = ["high", "medium", "low", "none"] as const;
export type TaskPriority = (typeof TASK_PRIORITIES)[number];

export const PUSH_PLATFORMS = ["ios", "macos", "web"] as const;
export type PushPlatform = (typeof PUSH_PLATFORMS)[number];

export const MEMBER_ROLES = ["owner", "member"] as const;
export type MemberRole = (typeof MEMBER_ROLES)[number];

// MARK: - Rows

type UUID = string;
/** ISO-8601 timestamp, as PostgREST returns timestamptz. */
type Timestamp = string;
type Json = string | number | boolean | null | Json[] | { [key: string]: Json };

export interface Workspace {
  id: UUID;
  name: string;
  owner_id: UUID;
  created_at: Timestamp;
}

export interface WorkspaceMember {
  workspace_id: UUID;
  user_id: UUID;
  role: MemberRole;
  created_at: Timestamp;
}

/** A machine that hosts agents: the Mac app, or later a cloud runner. */
export interface Desk {
  id: UUID;
  workspace_id: UUID;
  name: string;
  kind: DeskKind;
  app_version: string | null;
  last_seen_at: Timestamp | null;
  created_at: Timestamp;
}

export interface Project {
  id: UUID;
  workspace_id: UUID;
  name: string;
  /** GhosttiesCore.GhostCharacter raw value. */
  ghost_character: string | null;
  repo_url: string | null;
  /** The Mac app's Project.id, so the desk can match rows to local projects. */
  desktop_project_id: UUID | null;
  last_active_at: Timestamp | null;
  created_at: Timestamp;
}

export interface Agent {
  id: UUID;
  workspace_id: UUID;
  role: AgentRole;
  name: string;
  /** Null for the chief of staff; set for general managers and workers. */
  project_id: UUID | null;
  /** The general manager or chief of staff this agent reports to. */
  parent_agent_id: UUID | null;
  /** Where it runs. Null means not attached to a desk right now. */
  desk_id: UUID | null;
  status: AgentStatus;
  /** One line on what it is doing now ("Running tests on fix/hover"). */
  summary: string | null;
  branch: string | null;
  ghost_character: string | null;
  last_activity_at: Timestamp | null;
  created_at: Timestamp;
}

export interface Conversation {
  id: UUID;
  workspace_id: UUID;
  agent_id: UUID;
  title: string | null;
  created_by: UUID | null;
  last_message_at: Timestamp | null;
  created_at: Timestamp;
}

export interface Message {
  id: UUID;
  workspace_id: UUID;
  conversation_id: UUID;
  author_kind: AuthorKind;
  author_user_id: UUID | null;
  author_agent_id: UUID | null;
  kind: MessageKind;
  body: string;
  /** Kind-specific extras: ask_id for "ask"/"answer", task_id for "handoff". */
  payload: Json;
  /** Generated by the sender for optimistic UI; unique per conversation. */
  client_id: UUID | null;
  created_at: Timestamp;
}

export interface AskOption {
  id: string;
  label: string;
  /** What happens if picked. */
  detail?: string;
}

/** An agent waiting on a human. Every open ask is a "needs you" item. */
export interface Ask {
  id: UUID;
  workspace_id: UUID;
  agent_id: UUID;
  conversation_id: UUID;
  kind: AskKind;
  prompt: string;
  options: AskOption[];
  recommended_option_id: string | null;
  status: AskStatus;
  answer: AskAnswer | null;
  answered_by: UUID | null;
  answered_at: Timestamp | null;
  created_at: Timestamp;
}

export type AskAnswer =
  | { option_id: string; text?: string }
  | { text: string; option_id?: undefined };

export interface Task {
  id: UUID;
  workspace_id: UUID;
  project_id: UUID | null;
  agent_id: UUID | null;
  title: string;
  lane: TaskLane;
  priority: TaskPriority;
  branch: string | null;
  body: string;
  source: string | null;
  source_id: string | null;
  created_at: Timestamp;
  updated_at: Timestamp;
}

export interface ConversationRead {
  conversation_id: UUID;
  user_id: UUID;
  last_read_at: Timestamp;
}

export interface PushToken {
  id: UUID;
  user_id: UUID;
  platform: PushPlatform;
  token: string;
  created_at: Timestamp;
  last_seen_at: Timestamp;
}

/** Table name -> row type, for typed `from(...)` helpers. */
export interface Tables {
  workspaces: Workspace;
  workspace_members: WorkspaceMember;
  desks: Desk;
  projects: Project;
  agents: Agent;
  conversations: Conversation;
  messages: Message;
  asks: Ask;
  tasks: Task;
  conversation_reads: ConversationRead;
  push_tokens: PushToken;
}
export type TableName = keyof Tables;

// MARK: - RPCs (call with supabase.rpc(name, args))

export interface Rpcs {
  /** Idempotent on (conversation_id, client_id): a retry returns the first row. */
  send_message: {
    args: { p_conversation_id: UUID; p_body: string; p_client_id: UUID };
    returns: Message;
  };
  /** Opens a conversation with an agent and sends the first message. */
  start_conversation: {
    args: { p_agent_id: UUID; p_body: string; p_client_id: UUID; p_title?: string | null };
    returns: Conversation;
  };
  /** Answers an open ask and posts the answer into its conversation. */
  answer_ask: {
    args: { p_ask_id: UUID; p_answer: AskAnswer };
    returns: Ask;
  };
  mark_conversation_read: {
    args: { p_conversation_id: UUID };
    returns: null;
  };
  /** Upserts the caller's APNs device token (hex) or web push endpoint. */
  register_push_token: {
    args: { p_platform: PushPlatform; p_token: string };
    returns: PushToken;
  };
  /** Desk liveness. The desk calls this every 30s; offline after 90s. */
  desk_heartbeat: {
    args: { p_desk_id: UUID; p_app_version?: string | null };
    returns: Desk;
  };
}
export type RpcName = keyof Rpcs;

export const DESK_HEARTBEAT_SECONDS = 30;
export const DESK_OFFLINE_AFTER_SECONDS = 90;

// MARK: - Realtime

/**
 * Durable changes arrive as postgres_changes on these tables, filtered by
 * `workspace_id=eq.<id>`. RLS decides what each client receives.
 */
export const REALTIME_TABLES = [
  "messages",
  "asks",
  "agents",
  "conversations",
  "tasks",
  "desks",
] as const satisfies readonly TableName[];

/**
 * Ephemeral traffic (typing, streamed partial replies, desk presence) uses a
 * private Broadcast/Presence channel per workspace. Join with
 * `{ config: { private: true } }`.
 */
export const workspaceChannel = (workspaceId: UUID) => `workspace:${workspaceId}` as const;

export interface BroadcastEvents {
  /** A user or agent is composing in a conversation. */
  typing: { conversation_id: UUID; author_kind: AuthorKind; author_id: UUID };
  /**
   * Partial agent reply while it streams. The final text lands as a Message
   * whose client_id equals stream_id, so clients swap the draft for the row.
   */
  agent_delta: { conversation_id: UUID; agent_id: UUID; stream_id: UUID; text: string; done: boolean };
}
export type BroadcastEvent = keyof BroadcastEvents;

/** Presence payload each desk tracks on the workspace channel. */
export interface DeskPresence {
  desk_id: UUID;
  kind: DeskKind;
  app_version: string | null;
}

// MARK: - View helpers shared by both clients

/** Agents that need a human, in the order the Mac sidebar sorts them. */
export const NEEDS_YOU_STATUSES: readonly AgentStatus[] = ["needs_permission", "needs_input"];

export function isDeskOnline(desk: Pick<Desk, "last_seen_at">, now: Date = new Date()): boolean {
  if (!desk.last_seen_at) return false;
  return now.getTime() - new Date(desk.last_seen_at).getTime() < DESK_OFFLINE_AFTER_SECONDS * 1000;
}

export function taskLaneLabel(lane: TaskLane): string {
  return lane === "done" ? "graveyard" : lane;
}
