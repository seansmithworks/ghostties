import Foundation

// Codable mirror of the cloud contract (`cloud/contract/index.ts`), the rows
// the backend returns with their snake_case keys. Replace with the shared Swift
// contract target once it lands in `cli/`; screens only see these names.

enum AgentRole: String, Codable, Sendable {
    case chiefOfStaff = "chief_of_staff"
    case generalManager = "general_manager"
    case worker
}

/// Same vocabulary as the Mac sidebar's `ClaudeStateStore.Kind`, plus offline.
enum AgentStatus: String, Codable, Sendable {
    case busy, idle, ended, offline
    case needsInput = "needs_input"
    case needsPermission = "needs_permission"

    var needsYou: Bool { self == .needsInput || self == .needsPermission }
    var isGone: Bool { self == .ended || self == .offline }

    var label: String {
        switch self {
        case .busy: "Working"
        case .idle: "Idle"
        case .needsInput: "Needs you"
        case .needsPermission: "Needs permission"
        case .ended: "Ended"
        case .offline: "Offline"
        }
    }
}

enum DeskKind: String, Codable, Sendable { case mac, cloud }
enum AuthorKind: String, Codable, Sendable { case user, agent, system }
enum MessageKind: String, Codable, Sendable { case text, status, ask, answer, handoff }
enum AskKind: String, Codable, Sendable { case question, permission, decision }
enum AskStatus: String, Codable, Sendable { case open, answered, expired, cancelled }

struct Desk: Codable, Identifiable, Hashable, Sendable {
    var id: String
    var workspaceId: String
    var name: String
    var kind: DeskKind
    var appVersion: String?
    var lastSeenAt: Date?
    var createdAt: Date

    /// Matches the contract's `isDeskOnline`: seen within 90 seconds.
    func isOnline(now: Date = .now) -> Bool {
        guard let lastSeenAt else { return false }
        return now.timeIntervalSince(lastSeenAt) < 90
    }
}

struct Project: Codable, Identifiable, Hashable, Sendable {
    var id: String
    var workspaceId: String
    var name: String
    var ghostCharacter: String?
    var repoUrl: String?
    var lastActiveAt: Date?
    var createdAt: Date
}

struct Agent: Codable, Identifiable, Hashable, Sendable {
    var id: String
    var workspaceId: String
    var role: AgentRole
    var name: String
    var projectId: String?
    var parentAgentId: String?
    var deskId: String?
    var status: AgentStatus
    /// One line on what it is doing now.
    var summary: String?
    var branch: String?
    var ghostCharacter: String?
    var lastActivityAt: Date?
    var createdAt: Date
}

struct Conversation: Codable, Identifiable, Hashable, Sendable {
    var id: String
    var workspaceId: String
    var agentId: String
    var title: String?
    var createdBy: String?
    var lastMessageAt: Date?
    var createdAt: Date
}

/// The kind-specific extras the app reads. Unknown keys are ignored.
struct MessagePayload: Codable, Hashable, Sendable {
    var askId: String?
    var taskId: String?
}

struct Message: Codable, Identifiable, Hashable, Sendable {
    var id: String
    var workspaceId: String
    var conversationId: String
    var authorKind: AuthorKind
    var authorUserId: String?
    var authorAgentId: String?
    var kind: MessageKind
    var body: String
    var payload: MessagePayload
    /// Generated by the sender for optimistic UI; unique per conversation.
    var clientId: String?
    var createdAt: Date
}

struct AskOption: Codable, Identifiable, Hashable, Sendable {
    var id: String
    var label: String
    /// What happens if picked.
    var detail: String?
}

struct AskAnswer: Codable, Hashable, Sendable {
    var optionId: String?
    var text: String?
}

/// An agent waiting on a human. Every open ask is a "needs you" item.
struct Ask: Codable, Identifiable, Hashable, Sendable {
    var id: String
    var workspaceId: String
    var agentId: String
    var conversationId: String
    var kind: AskKind
    var prompt: String
    var options: [AskOption]
    var recommendedOptionId: String?
    var status: AskStatus
    var answer: AskAnswer?
    var answeredBy: String?
    var answeredAt: Date?
    var createdAt: Date
}

extension JSONDecoder {
    /// Decodes PostgREST rows: snake_case keys, ISO-8601 timestamps with or without fractions.
    static func contract() -> JSONDecoder {
        let decoder = JSONDecoder()
        decoder.keyDecodingStrategy = .convertFromSnakeCase
        decoder.dateDecodingStrategy = .custom { decoder in
            let string = try decoder.singleValueContainer().decode(String.self)
            let formatter = ISO8601DateFormatter()
            formatter.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
            if let date = formatter.date(from: string) { return date }
            formatter.formatOptions = [.withInternetDateTime]
            if let date = formatter.date(from: string) { return date }
            throw DecodingError.dataCorrupted(
                .init(codingPath: decoder.codingPath, debugDescription: "Not an ISO-8601 date: \(string)")
            )
        }
        return decoder
    }
}
